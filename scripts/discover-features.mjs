import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const manifestName = "feature.manifest.json";
const catalogRelativePath = "apps/web/src/generated-feature-catalog.ts";

function assertManifest(manifest, directoryName) {
  if (!manifest || manifest.manifestVersion !== 1) {
    throw new Error("Unsupported feature manifest version in " + directoryName);
  }
  if (manifest.id !== directoryName || !/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(manifest.id)) {
    throw new Error("Feature manifest ID must match its lowercase kebab-case directory: " + directoryName);
  }
  if (manifest.entryPoint !== "packages/features/" + directoryName + "/index.ts") {
    throw new Error("Feature manifest must use its canonical public entry point: " + directoryName);
  }
  if (typeof manifest.extensionExport !== "string" ||
      !/^[A-Z][A-Z0-9_]*_FEATURE_EXTENSION$/.test(manifest.extensionExport)) {
    throw new Error("Invalid feature extension export in manifest: " + directoryName);
  }
}

function renderCatalog(features) {
  const imports = features.map((feature, index) => {
    const alias = "discoveredFeatureExtension" + (index + 1);
    const from = "../../../packages/features/" + feature.id + "/index";
    return { alias, line: `import { ${feature.extensionExport} as ${alias} } from "${from}";` };
  });
  return [
    "/* Generated by scripts/discover-features.mjs. Do not edit manually. */",
    'import type { FeatureExtensionDefinition } from "../../../packages/core/src/feature-extension";',
    ...imports.map(item => item.line),
    "",
    "export const DISCOVERED_FEATURE_EXTENSIONS: readonly FeatureExtensionDefinition[] = Object.freeze([",
    ...imports.map(item => "  " + item.alias + ","),
    "]);",
    "",
  ].join("\n");
}

/**
 * Discover explicitly manifested feature packages and emit a statically linked,
 * deterministic application catalogue. This is build-time discovery, not runtime
 * directory scanning or dynamic code loading.
 */
export async function generateFeatureCatalog({ root = process.cwd(), check = false } = {}) {
  const featureRoot = path.join(root, "packages", "features");
  const catalogPath = path.join(root, catalogRelativePath);
  const directories = (await readdir(featureRoot, { withFileTypes: true }))
    .filter(entry => entry.isDirectory())
    .map(entry => entry.name)
    .sort((left, right) => left < right ? -1 : left > right ? 1 : 0);
  const features = [];

  for (const directoryName of directories) {
    const manifestPath = path.join(featureRoot, directoryName, manifestName);
    let raw;
    try {
      raw = await readFile(manifestPath, "utf8");
    } catch (error) {
      if (error?.code === "ENOENT") continue;
      throw error;
    }

    let manifest;
    try {
      manifest = JSON.parse(raw);
    } catch {
      throw new Error("Invalid JSON in feature manifest: " + directoryName);
    }
    assertManifest(manifest, directoryName);

    const publicEntryPath = path.join(featureRoot, directoryName, "index.ts");
    const publicEntry = await readFile(publicEntryPath, "utf8");
    const exportPattern = new RegExp(
      "export\\s*\\{[^}]*\\b" + manifest.extensionExport + "\\b[^}]*\\}",
      "s",
    );
    if (!exportPattern.test(publicEntry)) {
      throw new Error("Feature public entry point does not export " + manifest.extensionExport + ": " + directoryName);
    }
    features.push(manifest);
  }

  const ids = new Set();
  for (const feature of features) {
    if (ids.has(feature.id)) throw new Error("Duplicate discovered feature ID: " + feature.id);
    ids.add(feature.id);
  }

  const generated = renderCatalog(features);
  if (check) {
    let current;
    try {
      current = await readFile(catalogPath, "utf8");
    } catch {
      throw new Error("Generated feature catalogue is missing; run npm run features:discover");
    }
    if (current !== generated) {
      throw new Error("Generated feature catalogue is stale; run npm run features:discover");
    }
    return generated;
  }

  await mkdir(path.dirname(catalogPath), { recursive: true });
  await writeFile(catalogPath, generated, "utf8");
  return generated;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  try {
    await generateFeatureCatalog({ check });
    console.log(check ? "Feature catalogue is current." : "Generated deterministic feature catalogue.");
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
